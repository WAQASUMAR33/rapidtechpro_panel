async function seedAllProjects() {
  console.log('Seeding 15 RapidTechPro Company Projects...');
  
  const allCategories = await prisma.category.findMany();
  const allTechs = await prisma.technology.findMany();

  for (const p of projectsData) {
    const matchedCategories = allCategories
      .filter(c => p.categoryNames.includes(c.name))
      .map(c => ({ id: c.id }));

    const matchedTechs = allTechs
      .filter(t => p.techNames.includes(t.name))
      .map(t => ({ id: t.id }));

    const existing = await prisma.project.findUnique({ where: { slug: p.slug } });

    if (existing) {
      await prisma.project.update({
        where: { id: existing.id },
        data: {
          title: p.title,
          keyword: p.keyword,
          metaTitle: p.metaTitle,
          metaDescription: p.metaDescription,
          canonicalTag: p.canonicalTag,
          mainImage: p.mainImage,
          bannerImage: p.bannerImage,
          projectUrl: p.projectUrl,
          location: p.location,
          client: p.client,
          duration: p.duration,
          shortDescription: p.shortDescription,
          blog: p.blog,
          strategy: p.strategy,
          challenge: p.challenge,
          processSteps: p.processSteps,
          features: p.features,
          results: p.results,
          successPoints: p.successPoints,
          innovation: p.innovation,
          adaptableHeading: p.adaptableHeading,
          adaptableDescription: p.adaptableDescription,
          categories: {
            set: matchedCategories
          },
          technologies: {
            set: matchedTechs
          }
        }
      });
      console.log('🔄 Updated:', p.title);
    } else {
      await prisma.project.create({
        data: {
          title: p.title,
          slug: p.slug,
          keyword: p.keyword,
          metaTitle: p.metaTitle,
          metaDescription: p.metaDescription,
          canonicalTag: p.canonicalTag,
          mainImage: p.mainImage,
          bannerImage: p.bannerImage,
          projectUrl: p.projectUrl,
          location: p.location,
          client: p.client,
          duration: p.duration,
          shortDescription: p.shortDescription,
          blog: p.blog,
          strategy: p.strategy,
          challenge: p.challenge,
          processSteps: p.processSteps,
          features: p.features,
          results: p.results,
          successPoints: p.successPoints,
          innovation: p.innovation,
          adaptableHeading: p.adaptableHeading,
          adaptableDescription: p.adaptableDescription,
          categories: {
            connect: matchedCategories
          },
          technologies: {
            connect: matchedTechs
          }
        }
      });
      console.log('✅ Created:', p.title);
    }
  }

  const finalCount = await prisma.project.count();
  console.log(`\n🎉 All projects successfully saved to database! Total projects: ${finalCount}`);
}

seedAllProjects().catch(console.error).finally(() => prisma.$disconnect());
